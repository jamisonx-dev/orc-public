#!/bin/bash
# Assign a module's audio output to a card in the per-host-jackd model
# (2026-09-22).  Run as root (the web calls it via sudo; passwordless sudo is
# available on this box).
#
#   orc1_assign_module_out.sh <module> <card>     # -> card gets its own jackd
#   orc1_assign_module_out.sh <module> main       # -> back to the default server
#
# Model (decided with owner): OWN-JACKD WINS for module outs. Routing a module
# to card X gives X its OWN named jackd (jackd -n X) and STOPS any zita bridge on
# X (the ALSA device is exclusive -- a card cannot be both bridged into the
# default graph and owned by its own server). Bridges stay only for capture. When
# a per-card server has no module left, it is AUTO-STOPPED.
#
# The module host attaches to server X via JACK_SERVER=X (set in a drop-in) and
# self-connects to X's physical outs. The drop-in persists the assignment across
# boot (Requires= pulls X's jackd up for the assigned module).
set -u

MOD="${1:?usage: orc1_assign_module_out.sh <module> <card|main>}"
CARD="${2:?usage: orc1_assign_module_out.sh <module> <card|main>}"

# module key -> systemd unit. Keep in step with cfg.MODULE_KEYS hosts.
case "$MOD" in
    poly)    UNIT="orc1-poly.service" ;;
    chip)    UNIT="orc1-chip.service" ;;
    drum)    UNIT="orc1-drum.service" ;;
    mono)    UNIT="orc1-mono.service" ;;
    sampler) UNIT="orc1-sampler.service" ;;
    *) echo "unknown module: $MOD" >&2; exit 2 ;;
esac
DROPDIR="/etc/systemd/system/${UNIT}.d"
DROPIN="${DROPDIR}/50-jack-server.conf"

card_exists() { grep -qE "^\s*[0-9]+\s+\[$1 *\]" /proc/asound/cards; }

# The card the DEFAULT (nameless) jackd owns -- routing a module "to" it must be
# the same as reverting to main, NOT a second jackd on a device the default
# already holds (which would fail 'device busy' and, via the start-check below,
# abort). Parse the running default server's -dhw:<card> (the jackd whose args
# before -dalsa carry no server-name -n).
default_card() {
    local p a pre
    for p in $(pgrep -x jackd); do
        a="$(tr '\0' ' ' < "/proc/$p/cmdline" 2>/dev/null)"
        pre=" ${a%%-dalsa*} "
        case "$pre" in
            *" -n "*) : ;;                                  # a named server, skip
            *) echo "$a" | grep -oE 'dhw:[^ ]+' | head -1 | cut -d: -f2; return ;;
        esac
    done
}
MAINCARD="$(default_card)"
[ -n "$MAINCARD" ] && [ "$CARD" = "$MAINCARD" ] && CARD="main"

# Which per-card servers are still needed = the JACK_SERVER of every module
# drop-in.  Any active orc1-jackd@X not named there gets stopped.
autostop_unused() {
    local needed p unit inst
    needed=" $(grep -hoE 'JACK_SERVER=\S+' /etc/systemd/system/orc1-*.service.d/50-jack-server.conf 2>/dev/null | cut -d= -f2 | tr '\n' ' ') "
    for unit in $(systemctl list-units --state=active --no-legend 'orc1-jackd@*' 2>/dev/null | awk '{print $1}'); do
        inst="${unit#orc1-jackd@}"; inst="${inst%.service}"
        case "$needed" in
            *" $inst "*) : ;;                       # still referenced
            *) echo "[assign] auto-stopping unused server orc1-jackd@$inst"
               systemctl stop "orc1-jackd@$inst" ;;
        esac
    done
}

write_main_dropin() {
    # The base units carry NO jackd coupling; the drop-in always supplies it.
    # For the default server: order after + bind to orc1-jackd (the proven
    # cascade -- a main-card switch restarts orc1-jackd and this restarts the host
    # so it reconnects). No JACK_SERVER => the host opens the default server.
    mkdir -p "$DROPDIR"
    cat > "$DROPIN" <<EOF
# Generated by orc1_assign_module_out.sh -- ${MOD} on the DEFAULT (main) server.
[Unit]
After=orc1-jackd.service
BindsTo=orc1-jackd.service
EOF
}

if [ "$CARD" = "main" ] || [ "$CARD" = "default" ] || [ -z "$CARD" ]; then
    # Revert to the default server: WRITE the main drop-in (do not just delete --
    # the base unit no longer couples to jackd, so a missing drop-in would leave
    # the host with no ordering/bind at all).
    write_main_dropin
    systemctl daemon-reload
    systemctl restart "$UNIT"
    autostop_unused
    echo "[assign] $MOD -> main (default server)"
    exit 0
fi

card_exists "$CARD" || { echo "no such card: $CARD" >&2; exit 2; }

# 1) own-jackd wins: stop any bridge holding this card (generic + dedicated).
for u in "orc1-bridge@${CARD}.out" "orc1-bridge@${CARD}.in"; do
    systemctl is-active --quiet "$u" && { echo "[assign] stopping bridge $u"; systemctl stop "$u"; }
done
# dedicated bridge units (pisound/PerformVE) live under different names; the web
# passes the plain card name, so also stop the well-known ded units by card.
case "$CARD" in
    pisound)   for u in pisound-in pisound-out; do systemctl is-active --quiet "$u" && systemctl stop "$u"; done ;;
    PerformVE) for u in performve-in performve-out; do systemctl is-active --quiet "$u" && systemctl stop "$u"; done ;;
esac

# 2) bring up this card's own jackd (idempotent) -- and VERIFY it actually came
#    up before rebinding. A failed start (device busy, unsupported rate, card
#    gone) must NOT leave the module Wanting a dead server and itself dead while
#    the caller sees success: abort here, leaving the module on its current
#    server untouched.
systemctl start "orc1-jackd@${CARD}"
for _ in 1 2 3 4 5 6 7 8; do
    systemctl is-active --quiet "orc1-jackd@${CARD}" && break
    sleep 0.5
done
if ! systemctl is-active --quiet "orc1-jackd@${CARD}"; then
    echo "[assign] ERROR: orc1-jackd@${CARD} failed to start -- $MOD left unchanged" >&2
    exit 3
fi

# 3) rebind the module unit to server X (reset the list directives, then set).
mkdir -p "$DROPDIR"
# The base unit carries no jackd coupling, so no list-reset is needed (the reset
# did not work on this systemd anyway -- see the base-unit comment). Bind to THIS
# card's server only. Wants (not Requires) so an absent/removable card does not
# hard-block the host from starting -- the host then falls back to the default
# server (see the JACK_SERVER handling in the *_host.py main()).
cat > "$DROPIN" <<EOF
# Generated by orc1_assign_module_out.sh -- routes ${MOD} to card ${CARD}'s own
# jackd (per-host-jackd model). Remove via: orc1_assign_module_out.sh ${MOD} main
[Unit]
After=orc1-jackd@${CARD}.service
Wants=orc1-jackd@${CARD}.service
BindsTo=orc1-jackd@${CARD}.service

[Service]
Environment=JACK_SERVER=${CARD}
EOF

# 4) apply + restart the host (attaches to server X, self-connects to its outs),
#    then confirm it actually came active -- don't report success on a dead host.
systemctl daemon-reload
systemctl restart "$UNIT"
for _ in 1 2 3 4 5 6; do
    systemctl is-active --quiet "$UNIT" && break
    sleep 0.5
done
if ! systemctl is-active --quiet "$UNIT"; then
    echo "[assign] ERROR: $UNIT did not come active after rebinding to $CARD" >&2
    exit 4
fi

# 5) auto-stop any per-card server nothing needs any more.
autostop_unused
echo "[assign] $MOD -> $CARD (own jackd); JACK_SERVER=$CARD"
exit 0
